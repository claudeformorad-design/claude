/**
 * نص البحث داخل مرشّحات PostgREST (or/ilike): تُحذف الرموز التي لها معنى في صيغة المرشّح
 * (الفاصلة والأقواس وعلامات التنصيص والنجمة والنسبة والشرطة المائلة العكسية والنقطتان)،
 * فلا يستطيع نص المستخدم أو نص المساعد الذكي إضافة شروط إلى الاستعلام. ويُقصّ لطول معقول.
 */
export function searchTerm(q: string | null | undefined): string {
  return (q ?? "").replace(/[%,()*"'\\:]/g, " ").replace(/\s+/g, " ").trim().slice(0, 100);
}
